"""In-game drive test: buy each vehicle, run it on a test line, and check that
it moves, how fast it gets, that its sound set loaded, that its horn is
audible, and photograph it moving, close up, from the cab and at night.

    python port.py drive <vehicle> ...       # vehicle config names
    python port.py drive --all
    options: --rebuild          build the test line again (new cached save)
             --save <name>      use your own savegame instead of the test line
             --loco <modId>::/<dir>/<model>.mdl   engine for unpowered cars

The game must be closed; it is started, driven by a --script (see
game_smoke.py and AGENTS.md), and quits by itself.

The test line is made by the script, not shipped: a new game (fixed seed),
the flattest straight north-south strip of the map, and on it a depot, a
station, high-speed electrified track and a second station, plus a line
between the two. The strip is the longest the map has (4.5 km on the default
map: 3.6 km between the stations, where a single 160 km/h car reaches top
speed and a 9-car EMU gets to ~150);
the hand-made save this replaced capped every vehicle at ~100 km/h. The first
run saves it as TESTLINE_SAVE; later runs load that save with the mods under
test (about half a minute less than building it). --rebuild, or a change of
TESTLINE_SAVE, makes a new one.

Per vehicle mod, one test unit: its shortest consist (.mu.lua) if it has
any, so an EMU runs with its cab cars; else its first powered model; else its
first car behind a borrowed locomotive (--loco, or "helper_loco" in
local_settings.json; else whatever powered model loaded first).

Checks and where they come from:
    bought     makeVehicleBuyCmd succeeded at the depot
    maxSpeed   max MOVE_PATH dyn.speed on the line; topSpeed is the lowest
               landVehicle.topSpeed in the unit. "reached" within 3 %;
               "capped" when it levelled off below that for 15 s (wrong
               power, weight or topSpeed); neither = the line ended while it
               was still accelerating, which says nothing is wrong
    soundSet   the model's soundConfig.soundSet.name resolves in soundSetRep
    horn       PC audio output (WASAPI loopback) louder right after
               gui.sound.letVehicleHorn than just before it
    shots      following camera while moving, closer view, cockpit view,
               and from four sides at 23:00 for the lights

Results: logs/drive/<run>/results.json and the screenshots beside it.
"""
