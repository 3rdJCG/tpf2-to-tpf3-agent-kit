class Recorder(threading.Thread):
    """Records the default speaker's output (loopback) as RMS per 0.1 s."""

    def __init__(self):
        super().__init__(daemon=True)
        self.rms, self.t0, self.stop = [], None, False

    def run(self):
        import warnings
        import numpy as np
        import soundcard as sc
        # "data discontinuity in recording" every few blocks while the game
        # loads; harmless for an RMS level
        warnings.filterwarnings("ignore", category=sc.SoundcardRuntimeWarning)
        mic = sc.get_microphone(id=str(sc.default_speaker().name), include_loopback=True)
        with mic.recorder(samplerate=48000) as rec:
            self.t0 = time.time()
            while not self.stop:
                d = rec.record(numframes=4800)
                self.rms.append((time.time(), float(np.sqrt((d ** 2).mean()))))

    def level(self, a, b, how=max):
        xs = sorted(r for t, r in self.rms if a <= t < b)
        if not xs:
            return 0.0
        return xs[len(xs) // 2] if how == "median" else how(xs)


def log_times(path, tag):
    """Wall-clock times of DRIVE lines with `tag`, from the game log."""
    import calendar
    out = []
    for l in open(path, encoding="utf-8", errors="replace"):
        if tag in l:
            m = re.match(r"\[(\d+)-(\d+)-(\d+) (\d+):(\d+):(\d+)Z", re.sub(r"\x1b\[[0-9;]*m", "", l))
            if m:
                t = calendar.timegm(tuple(int(x) for x in m.groups()) + (0, 0, 0))
                out.append((t, l.split(tag, 1)[1].strip()))
    return out


def drive_sheet(outdir, w=360):
    """One row per unit, one column per shot; night shots brightened 2.5x."""
    from PIL import Image, ImageDraw, ImageEnhance
    shots = sorted(f for f in os.listdir(outdir) if re.match(r"\d{3}_.*\.png$", f))
    rows = {}
    for f in shots:
        m = re.match(r"\d{3}_(.*)_([a-z]+\d?)\.png$", f)
        if m:
            rows.setdefault(m.group(1), []).append((m.group(2), f))
    if not rows:
        return None
    h = int(w * 9 / 16)
    cols = max(len(v) for v in rows.values())
    sheet = Image.new("RGB", (cols * w, len(rows) * (h + 20)), (24, 24, 24))
    d = ImageDraw.Draw(sheet)
    for r, (unit, items) in enumerate(rows.items()):
        y = r * (h + 20)
        d.text((4, y + 4), unit, fill=(255, 255, 255))
        for c, (tag, f) in enumerate(items):
            im = Image.open(os.path.join(outdir, f)).convert("RGB").resize((w, h))
            if tag.startswith("night"):
                im = ImageEnhance.Brightness(im).enhance(2.5)
            sheet.paste(im, (c * w, y + 20))
            d.text((c * w + 4, y + 22), tag, fill=(255, 255, 0))
    path = os.path.join(outdir, "sheet.png")
    sheet.save(path)
    return path


